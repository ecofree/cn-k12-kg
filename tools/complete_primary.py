def enrich_card(source, topic, bank=None):
    """Pure completion layer shared by the writer and source-rebuild regressions."""
    tid = topic['id']
    c = copy.deepcopy(source)
    c.update(topicId=tid, name=topic['name'])
    c.update(copy.deepcopy(PATCHES.get(tid, {})))
    c['content_revision'] = {'author_type':'ai','date':'2026-10-26','teacher_review':'pending'}
    diagrams = {
        'm3a.1.3': ('primary-cube-net','A、B、C、D横排，E在B上、F在B下。折叠时逐面追踪位置。'),
        'm4a.5.2': ('primary-trapezoid-height','梯形ABCD中AB∥CD，DH⊥AB，DH是以AB为底的高。'),
        'm5a.1.1': ('primary-three-views','摆法为一行三列、高度1、2、1；图中依次是前面、右面、上面视图。'),
        'm4a.6.1': ('primary-bar-chart','示例数据：A班8人、B班12人、C班10人。纵轴从0开始，每格2人。'),
    }
    if tid in diagrams:
        src, alt = diagrams[tid]
        c['diagram'] = {'src':f'/static/diagrams/{src}.svg','alt':alt}
    if tid in GOALS:
        objectives = GOALS[tid]
        criteria = topic['mastery_criteria']
        assert len(objectives) == len(criteria), tid
        c['objective_coverage'] = [dict(criterion_index=i, title=criteria[i], **copy.deepcopy(g))
                                  for i,g in enumerate(objectives)]
    if tid in NEW:
        if bank is None:
            raise ValueError(f'{tid}: new cards require the current practice bank')
        from cnkg.evidence import question_policy
        qs = [q for q in bank if tid in q.get('topicIds', [q.get('topicId')])
              and question_policy(q)['practice_eligible']]
        qs.sort(key=lambda q: (q['type']=='choice', q['id']))
        c['practice'] = [dict(id=q['id'],note='完成后说清数量关系与每步依据。') for q in qs[:3]]
    return c


def write_cards():
    topics = {t['id']: t for t in json.loads((ROOT/'data/topics.json').read_text())}
    bank = json.loads((ROOT/'data/questions.json').read_text())
    for tid in GOALS:
        path = ROOT/'data/teach'/f'{tid}.json'
        source = NEW.get(tid) or json.loads(path.read_text())
        c = enrich_card(source, topics[tid], bank)
        path.write_text(json.dumps(c,ensure_ascii=False,indent=2)+'\n')
    for tid in set(PATCHES)-set(GOALS):
        path = ROOT/'data/teach'/f'{tid}.json'
        c = enrich_card(json.loads(path.read_text()), topics[tid], bank)
        path.write_text(json.dumps(c,ensure_ascii=False,indent=2)+'\n')
    print(f'小学新增完整卡 {len(NEW)}；目标覆盖 {len(GOALS)} 点。')


if __name__ == '__main__':
    import sys
    sys.path.insert(0,str(ROOT))
    write_cards()
