def main() -> None:
    import primary_lexicon
    import senior_lexicon

    out = {}
    for stage, rules in (("senior", senior_lexicon.RULES),
                         ("junior", JUNIOR),
                         ("primary", primary_lexicon.RULES)):
        for tid, (must, anyp, notp) in rules.items():
            out[tid] = {"stage": stage, "must": must, "any": anyp, "not": notp}
    path = ROOT / "data" / "kc_lexicon.json"
    path.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")

    from collections import Counter
    print(f"写入 {path.relative_to(ROOT)}：{len(out)} 条规则")
    print("按学段：", dict(Counter(v["stage"] for v in out.values())))

    # 覆盖率自检：每个知识点都必须有词典条目，否则它永远映射不出题
    topics = json.loads((ROOT / "data" / "topics.json").read_text(encoding="utf-8"))
    def stage_of(t):
        g = t.get("grade")
        return "primary" if g <= 6 else ("junior" if g <= 9 else "senior")
    missing = defaultdict(list)
    for t in topics:
        if t["id"] not in out:
            missing[stage_of(t)].append(t["id"])
    total_missing = sum(len(v) for v in missing.values())
    for s in ("primary", "junior", "senior"):
        n = sum(1 for t in topics if stage_of(t) == s)
        print(f"  {s}: 知识点 {n}  词典覆盖 {n - len(missing[s])}  "
              f"覆盖率 {(n - len(missing[s])) / n * 100:.1f}%")
    if total_missing:
        print(f"  未覆盖 {total_missing} 个：")
        for s, ids in missing.items():
            print(f"    {s}: {ids[:12]}")

    # 正则自检：一条坏正则会让整个映射器在运行时崩掉，必须在构建阶段拦住
    import re
    bad = []
    for tid, v in out.items():
        for grp in ("must", "any", "not"):
            for p in (v.get(grp) or []):
                try:
                    re.compile(p)
                except re.error as exc:
                    bad.append((tid, grp, p, str(exc)))
    if bad:
        print(f"\n  ✗ {len(bad)} 条正则无法编译：")
        for tid, grp, p, exc in bad[:20]:
            print(f"    {tid} [{grp}] {p!r}\n        -> {exc}")
        raise SystemExit(1)
    print("  正则自检：477 条规则全部可编译")

    # **must 的 AND 陷阱自检**
    # must 语义是「全部命中」，所以并列的候选词必须写在单条正则的 alternation 里。
    # 写成 must=['A', 'B'] 等于要求 A 和 B 同时出现——规则看着合理，
    # 但几乎匹配不到任何题，该知识点就一道题也没有，而且**不会报错**。
    # 实测因此封死了 6 个高中点 + 3 个初中点。
    traps = [(tid, v["must"]) for tid, v in out.items()
             if len(v.get("must") or []) >= 2
             and not all("|" in p for p in (v.get("must") or []))]
    if traps:
        print(f"\n  ⚠ {len(traps)} 条规则有 must 的 AND 陷阱（并列词应合并进单条正则）：")
        for tid, must in traps[:20]:
            print(f"    {tid:<14}must={must}")
        print("    （不阻断构建，但这些规则很可能匹配不到题）")
    else:
        print("  must 的 AND 陷阱自检：无")


if __name__ == "__main__":
    main()
