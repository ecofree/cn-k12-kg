CARDS, NEW = {}, {}


def parts(s):
    return s.split("｜") if isinstance(s, str) else s


def objective(explanation, prompt, answer, criteria):
    return dict(explanation=explanation, self_check=dict(prompt=prompt, reference_answer=answer, criteria=parts(criteria)))


def lesson(tid, hook, boundary, why, signals, steps, example, pitfalls, *goals):
    topic = TOPICS[tid]
    assert len(goals) == len(topic["mastery_criteria"]), tid
    coverage = [dict(criterion_index=i, title=title, **g) for i, (title, g) in enumerate(zip(topic["mastery_criteria"], goals))]
    prompt, calculation, answer, *verify = example
    ex = dict(prompt=prompt, steps=parts(calculation), answer=str(answer))
    if verify:
        ex["verify"] = verify[0]
    CARDS[tid] = dict(schema=1, review_status="draft", author="ai", topicId=tid,
        name=topic["name"], tier="core", hook=hook,
        definition=topic["description"] + boundary,
        why=why, when_to_use=parts(signals), steps=parts(steps), worked_example=ex,
        pitfalls=parts(pitfalls), objective_coverage=coverage,
        check="独立完成两项自检并保留推导或作图：" + "；".join(g["self_check"]["criteria"][0] for g in goals) + "。过程目标按下列量规逐项核对，不由一道客观题的得分代替。")


def question(tid, kind, prompt, answer, explanation, indices, **extra):
    rows = NEW.setdefault(tid, [])
    q = dict(id=f"{tid}-q{201 + len(rows)}", topicId=tid, topicIds=[tid], primaryTopicId=tid,
        type=kind, prompt=prompt, answer=str(answer), explanation=explanation,
        source="self-generated-completion", review_status="draft", author="ai", generated=True,
        difficulty="standard", difficulty_basis="需要应用本知识点的条件、关系或运算，非背诵匹配题",
        target_alignment="component_practice_only", diagnosis_eligible=False, for_diagnosis=False,
        tested_criterion_indices=indices,
        alignment_note="本题仅检查以下目标中的题设子任务：" + "；".join(TOPICS[tid]["mastery_criteria"][i] for i in indices) + "。完整推导、证明或方案设计由讲解卡的独立自检与量规检查。",
        **extra)
    rows.append(q)
    return q


def num(tid, prompt, expression, answer, explanation, indices):
    return question(tid, "numeric", prompt, answer, explanation, indices, verify=expression)


def choice(tid, prompt, options, correct, explanation, indices):
    return question(tid, "choice", prompt, f"o{correct}", explanation, indices,
                    choices=[dict(id=f"o{i+1}", text=s) for i, s in enumerate(options)])


def short(tid, prompt, answer, explanation, indices, accept=()):
    return question(tid, "short", prompt, answer, explanation, indices, accept=list(accept))


def finish(require_complete=True):
    expected = {tid for tid in TOPICS if TIERS[tid]["tier"] == "core"}
    if require_complete:
        assert set(CARDS) == expected, sorted(expected - set(CARDS))
    selected = {}
    for tid, card in CARDS.items():
        existing = [q for q in BASE if tid in q.get("topicIds", [q.get("topicId")]) and question_policy(q)["practice_eligible"]]
        gap = max(0, TIERS[tid]["practice_target"] - len(existing))
        additions = NEW.get(tid, [])[:gap]
        assert len(additions) == gap, (tid, gap, len(additions))
        selected[tid] = additions
        candidates = additions + existing
        independent = next(q for q in candidates if q["type"] != "choice")
        chosen = [independent] + [q for q in candidates if q["id"] != independent["id"]][:2]
        card["practice"] = [dict(id=q["id"], note="完成后核对解析中的条件与步骤；完整目标另做下方独立自检。") for q in chosen]
    bank = {q["id"]: q for q in BASE}
    for additions in selected.values():
        for q in additions:
            assert q["id"] not in bank, q["id"]
            bank[q["id"]] = q
            assert question_policy(q)["practice_eligible"], q["id"]
            if q["type"] == "numeric":
                assert check_question(q)["status"] == "pass", check_question(q)
            assert q["tested_criterion_indices"] and all(0 <= i < len(TOPICS[q["topicId"]]["mastery_criteria"]) for i in q["tested_criterion_indices"])
    for tid, card in CARDS.items():
        errs = check_card(card, TOPICS, bank)
        assert not errs, (tid, errs)
        assert len(card["pitfalls"]) >= 2
        for obj in card["objective_coverage"]:
            assert len(obj["self_check"]["criteria"]) >= 2
            assert len(obj["self_check"]["reference_answer"]) >= 8
        (ROOT / f"data/teach/{tid}.json").write_text(json.dumps(card, ensure_ascii=False, indent=1) + "\n")
    for volume, data in VOLUMES.items():
        if not set(data["topics"]) & set(CARDS):
            continue
        data["questions"] = [q for q in data["questions"] if q.get("source") != "self-generated-completion"]
        data["questions"] += [q for tid, qs in selected.items() if tid in data["topics"] for q in qs]
        (ROOT / f"data/content/{volume}.json").write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n")
    print(json.dumps({"cards": len(CARDS), "objectives": sum(len(c["objective_coverage"]) for c in CARDS.values()), "new_questions": sum(map(len, selected.values())), "by_volume": {v: {"cards": sum(t in CARDS for t in d["topics"]), "questions": sum(len(selected.get(t, [])) for t in d["topics"])} for v, d in VOLUMES.items()}}, ensure_ascii=False))


