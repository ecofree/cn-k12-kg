def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for card in CARDS:
        card = {"schema": 1, "review_status": "draft", "author": "hand", **card}
        path = OUT / f"{card['topicId']}.json"
        path.write_text(json.dumps(card, ensure_ascii=False, indent=1) + "\n",
                        encoding="utf-8")
        print(f"写入 {path.name}  {card['name']}")
    print(f"共 {len(CARDS)} 张")
    return 0


