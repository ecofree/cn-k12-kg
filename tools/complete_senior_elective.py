def main():
    registry = json.loads((ROOT / "data/content_sources.json").read_text(encoding="utf-8"))
    registered = {source["path"] for source in registry["content_sources"]}
    assert {str(p.relative_to(ROOT / "data")) for p in SOURCES} <= registered
    expected = {tid for tid in TOPICS if TIERS[tid]["tier"] == "core"}
    assert set(CARDS) == expected, ("missing or unexpected cards", expected ^ set(CARDS))
    assert len(CARDS) == 59
    assert sum(map(len, NEW.values())) == 189
    bank = {q["id"]: q for q in json.loads((ROOT / "data/questions.json").read_text(encoding="utf-8"))
            if q.get("completion_batch") != BATCH}
    for volume in VOLUMES:
        volume["questions"] = [q for q in volume["questions"] if q.get("completion_batch") != BATCH]
        for tid in volume["topics"]:
            for question in NEW.get(tid, []):
                assert question["id"] not in bank, ("question ID collision", question["id"])
                if question["type"] == "numeric":
                    result = check_question(question)
                    assert result["status"] == "pass", result
                assert question_policy(question)["practice_eligible"], question["id"]
                bank[question["id"]] = question
                volume["questions"].append(question)
    for tid, card in CARDS.items():
        eligible = [q for q in bank.values() if tid in q.get("topicIds", [q.get("topicId")])
                    and question_policy(q)["practice_eligible"]]
        assert len(eligible) >= TIERS[tid]["practice_target"], (tid, len(eligible))
        # 先取本次补充的不同目标练习，再取已有应用题；至少一道需要自己作答。
        eligible.sort(key=lambda q: (q.get("completion_batch") != BATCH,
                                    not q["id"].endswith(("-q101", "-q102")), q["id"]))
        chosen = eligible[:3]
        if not any(q["type"] != "choice" for q in chosen):
            nonchoice = next(q for q in eligible if q["type"] != "choice")
            chosen[-1] = nonchoice
        card["practice"] = [{"id": q["id"], "note": "完成后对照解析检查条件、步骤和结果：" + q["prompt"]}
                            for q in chosen]
        errors = check_card(card, TOPICS, bank)
        assert not errors, (tid, errors)
        for i, coverage in enumerate(card["objective_coverage"]):
            assert coverage["criterion_index"] == i
            assert coverage["title"] == TOPICS[tid]["mastery_criteria"][i]
            task = coverage["self_check"]
            assert task["prompt"] and task["reference_answer"] and len(task["criteria"]) >= 2
    for path, volume in zip(SOURCES, VOLUMES):
        path.write_text(json.dumps(volume, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    for tid, card in CARDS.items():
        (ROOT / "data/teach" / f"{tid}.json").write_text(
            json.dumps(card, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"写出 {len(CARDS)} 张完整卡、{sum(len(c['objective_coverage']) for c in CARDS.values())} 条目标过程任务、{sum(map(len, NEW.values()))} 道补充题。")
    for prefix, label in (("mh3.", "选必一"), ("mh4.", "选必二"), ("mh5.", "选必三")):
        print(label, "完整卡", sum(t.startswith(prefix) for t in CARDS),
              "新增题", sum(len(qs) for tid, qs in NEW.items() if tid.startswith(prefix)))
    print("已校验题目数值、卡结构、每目标索引、同主题可练引用与8题目标；独立学科审核及真实学生效果仍pending。")


if __name__ == "__main__":
    main()
