def project(pid, title, volume, standards, duration, brief, goals, materials, steps, rubric, notes):
    ids = [f'{pid}:o{i+1}' for i in range(len(goals))]
    p = dict(schema=1, id=pid, title=title, stage='primary',
             outline_refs=[dict(book_id=volume,title=title)],
             standard_ids=standards,
             standard_alignment_note='依据目录活动题名原创设计，关联所列课标中的数量关系、测量或表达要求；不是教材原文复制，也不代表完整覆盖相应课标条款。',
             duration_hint=duration,
             task_brief=brief, objectives=[dict(id=i,statement=s) for i,s in zip(ids,goals)],
             materials=materials,
             steps=[dict(title=t,objective_ids=[ids[i] for i in oi],instructions=ins,deliverable=d)
                    for t,oi,ins,d in steps],
             deliverables=[x[3] for x in steps],
             rubric=[dict(objective_ids=[ids[i] for i in oi],criterion=c,points=pts,example=ex)
                     for oi,c,pts,ex in rubric],
             assessment_note='按作品中可观察的过程逐项反馈。数值结果、关系解释、记录与修订分别评价；不以画面精美程度或一次自评判定掌握。',
             teacher_notes=notes, author_type='ai',review_status='draft',
             teacher_review=dict(status='pending'))
    outline=json.loads((ROOT/'data/outline.json').read_text())
    standards_by_id={s['id']:s for s in json.loads((ROOT/'data/standards.json').read_text())}
    errors=check_project(p,outline,standards_by_id)
    if errors:raise ValueError((pid,errors))
    (ROOT/'data/projects'/f'{pid}.json').write_text(json.dumps(p,ensure_ascii=False,indent=2)+'\n')


